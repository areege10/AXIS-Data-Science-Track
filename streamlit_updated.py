import subprocess
import time
import urllib.request
import os

# Streamlit configuration
PORT = 8501

# Start Streamlit only once
log_file = open("/content/streamlit.log", "w")

process = subprocess.Popen(
    [
        "streamlit",
        "run",
        "/content/app_Updated.py",
        "--server.port", str(PORT),
        "--server.address", "0.0.0.0",
        "--server.headless", "true"
    ],
    stdout=log_file,
    stderr=subprocess.STDOUT
)

print("Starting Streamlit...")

# Wait until Streamlit becomes available
server_ready = False

for i in range(30):
    try:
        response = urllib.request.urlopen(
            f"http://127.0.0.1:{PORT}/_stcore/health",
            timeout=2
        )

        if response.status == 200:
            server_ready = True
            break

    except Exception:
        time.sleep(2)

if server_ready:
    print("✅ Streamlit is running!")
    print("PID:", process.pid)
else:
    print("❌ Streamlit did not start successfully.")
    print("\nCheck the log below:")

    log_file.flush()

    with open("/content/streamlit.log", "r") as f:
        print(f.read()[-5000:])

