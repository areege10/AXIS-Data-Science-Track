def get_expected_features(model):

    """
    Get the feature names expected by the trained model.
    """

    if hasattr(model, "feature_names_in_"):

        return list(model.feature_names_in_)

    if hasattr(model, "named_steps"):

        for step in model.named_steps.values():

            if hasattr(step, "feature_names_in_"):

                return list(step.feature_names_in_)

    return None

def get_segmentation_features():

    """
    Get the exact segmentation feature names
    used during training.
    """

    if hasattr(segment_scaler, "feature_names_in_"):

        return list(segment_scaler.feature_names_in_)

    if hasattr(segment_imputer, "feature_names_in_"):

        return list(segment_imputer.feature_names_in_)

    return None


def create_model_input(model, customer_values):

    """
    Create a dataframe with the exact features
    required by the trained model.
    """

    features = get_expected_features(model)

    if features is None:

        raise ValueError(
            "Could not identify the model input features."
        )

    missing = [
        col for col in features
        if col not in customer_values
    ]

    if missing:

        raise ValueError(
            f"Missing model features: {missing}"
        )

    return pd.DataFrame(
        [[customer_values[col] for col in features]],
        columns=features
    )

def get_model_name(model):

    """
    Return the final estimator name.
    """

    if hasattr(model, "named_steps"):

        final_model = list(
            model.named_steps.values()
        )[-1]

        return final_model.__class__.__name__

    return model.__class__.__name__


def predict_churn(model, data):

    """
    Predict customer churn.

    Probability is displayed only if the
    selected model supports predict_proba.
    """

    prediction = int(
        model.predict(data)[0]
    )

    probability = None

    if hasattr(model, "predict_proba"):

        probabilities = model.predict_proba(data)[0]

        classes = list(model.classes_)

        if 1 in classes:

            probability = float(
                probabilities[classes.index(1)]
            )

    return prediction, probability


def get_segment_profiles():

    """
    Load descriptive K-Means profiles
    from the exported segmentation dataset.
    """

    if not SEGMENT_DATA_PATH.exists():

        return {}

    try:

        data = pd.read_csv(SEGMENT_DATA_PATH)

        required_columns = [
            "KMeans_Segment",
            "KMeans_Profile"
        ]

        if not all(
            col in data.columns
            for col in required_columns
        ):

            return {}

        profiles = {}

        for segment_id, group in data.groupby(
            "KMeans_Segment"
        ):

            profiles[segment_id] = (
                group["KMeans_Profile"]
                .mode()
                .iloc[0]
            )

        return profiles

    except Exception:

        return {}


